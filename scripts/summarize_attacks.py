"""Generate a provenance-linked white-box/transfer Markdown table; never runs attacks."""

from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import RESULTS_DIR
from src.data.preprocessing import atomic_write_bytes, sha256_file
from src.evaluation.artifacts import ArtifactStore
from src.evaluation.attack_results import validate_attack_report


def summary(path):
    path = Path(path).resolve()
    report = validate_attack_report(ArtifactStore(path.parent).json(path.name))
    identity = report["identity"]

    def safe(value):
        return (
            html.escape(str(value), quote=False)
            .replace("`", "&#96;")
            .replace("\n", " ")
            .replace("|", "&#124;")
        )

    lines = [
        "# White-box / black-box evidence table",
        "",
        "Generated by `scripts/summarize_attacks.py`; do not hand-edit.",
        "This summarizes recorded measurements, not a new experiment.",
        "",
        f"Input artifact: `{safe(path.name)}`; SHA-256 `{sha256_file(path)}`.",
        f"Compatibility identity: `{report['compatibility_id']}`.",
        f"Stage: `{safe(report.get('experiment_stage', 'frozen_baseline'))}`.",
        f"Generated experiment timestamp: `{safe(report['generated_at'])}`.",
        "",
        "Accuracy denominator: all selected rows. ASR denominator: each model's",
        "initially correct rows (both classes). Pending is not zero.",
        "A surrogate white-box result and target transfer result use identical",
        "perturbed samples; target white-box is independently optimized.",
        "",
        "| Attack / parameters | Knowledge | Evaluated model | Correct / all | ASR induced / clean-correct |",
        "|---|---|---|---:|---:|",
    ]
    for row in report["results"]:
        config = safe(json.dumps(row["parameters"], sort_keys=True))
        entries = [("white-box", "target", row["metrics"])]
        if "transfer" in row:
            entries += [
                ("surrogate white-box", "source", row["transfer"]["source_metrics"]),
                ("black-box transfer", "target", row["transfer"]["target_metrics"]),
            ]
        else:
            entries.append(("black-box transfer", "target", None))
        for mode, model, m in entries:
            correct = f"{m['attacked_correct']}/{m['samples']}" if m else "pending"
            asr = f"{m['successful_attacks']}/{m['asr_denominator']}" if m else "pending"
            lines.append(f"| {row['attack']} `{config}` | {mode} | {model} | {correct} | {asr} |")
    lines += [
        "",
        "## Exact comparison contracts",
        "",
        "```json",
        json.dumps(
            {"identity": identity, "constraint": report["constraint"]},
            indent=2,
            sort_keys=True,
            ensure_ascii=False,
            allow_nan=False,
        ),
        "```",
        "",
        "Scalar policy compliance is not coupled structural consistency, executable",
        "realizability or preserved behavior. Technical review and M1 remain separate.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=RESULTS_DIR / "attack_reference.json")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    if args.output.exists():
        parser.error("Refusing to overwrite an existing summary")
    content = summary(args.input)
    atomic_write_bytes(args.output, content.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
